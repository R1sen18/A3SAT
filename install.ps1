# A3SAT2 - A3Bot portable installer
# Run as Administrator from anywhere; all paths resolve relative to this script.
# Asks only for the essentials (token, guild ID, user IDs); everything else uses
# standard values. Run with -Advanced to also configure service names and paths.
# Run with -BotOnly to skip the SteamCMD check/install and only set up the bot
# itself (dependencies, .env_setup, service).
param([switch]$Advanced, [switch]$BotOnly)

$botDir  = Join-Path $PSScriptRoot "scripts\python"
$botFile = Join-Path $botDir "A3Bot.py"
$envFile = Join-Path $botDir ".env_setup"
$logsDir = Join-Path $PSScriptRoot "logs"
$service = "A3Bot"

Write-Host "== A3SAT2 - A3Bot installer ==" -ForegroundColor Cyan
Write-Host "Install location: $PSScriptRoot"

# 1. Sanity check: bot files present next to this script
if (-not (Test-Path $botFile)) {
    Write-Host "A3Bot.py not found at $botFile - keep the folder structure from the zip intact." -ForegroundColor Red
    exit 1
}

# 2. Find python: PATH first, then the known VM install
$python = (Get-Command python -ErrorAction SilentlyContinue).Source
if (-not $python) {
    $fallback = "C:\Users\Administrator\AppData\Local\Programs\Python\Python314\python.exe"
    if (Test-Path $fallback) { $python = $fallback }
}
if (-not $python) {
    Write-Host "Python not found in PATH or at the default location. Install Python 3.10+ first." -ForegroundColor Red
    exit 1
}
# A3Bot.py uses PEP 604 unions (`bool | None`) in its signatures, which are
# evaluated at import: on 3.9 or older the service restart-loops with a
# TypeError that is only visible in a3bot_stderr.log. Fail here instead.
$pyVer = (& $python -c "import sys; print('%d.%d' % sys.version_info[:2])" 2>$null)
if ($LASTEXITCODE -ne 0 -or -not $pyVer) {
    Write-Host "Could not determine the Python version of $python." -ForegroundColor Red
    exit 1
}
if ([version]$pyVer -lt [version]"3.10") {
    Write-Host "Python $pyVer found at $python, but A3Bot needs 3.10 or newer." -ForegroundColor Red
    Write-Host "Install a newer Python and make sure it comes first in PATH." -ForegroundColor Red
    exit 1
}
Write-Host "Using Python: $python (version $pyVer)"

# 3. Find nssm: next to this script first, then the A3SAT install
$nssm = Join-Path $PSScriptRoot "nssm.exe"
if (-not (Test-Path $nssm)) { $nssm = "C:\steamgames\a3server\A3SAT\nssm.exe" }
if (-not (Test-Path $nssm)) {
    Write-Host "nssm.exe not found - place it next to install.ps1 (download: https://nssm.cc)." -ForegroundColor Red
    exit 1
}
Write-Host "Using NSSM: $nssm"

# 4. Query configuration (skip if .env_setup already exists)
if (Test-Path $envFile) {
    Write-Host ".env_setup already exists - keeping it. Delete it and re-run to reconfigure." -ForegroundColor Yellow
} else {
    Write-Host ""
    Write-Host "-- Configuration --" -ForegroundColor Cyan
    Write-Host "Create your Discord application first: https://discord.com/developers/applications"
    Write-Host "(New Application -> Bot -> copy token; invite with scope bot+applications.commands)"
    Write-Host ""

    do { $botToken = Read-Host "Discord bot token" } while (-not $botToken)
    do { $guildId  = Read-Host "Discord server (guild) ID" } while ($guildId -notmatch '^\d+$')
    do { $userIds  = Read-Host "Authorized Discord user ID(s), comma-separated" } while ($userIds -notmatch '^\d+(\s*,\s*\d+)*$')
    $steamUser = Read-Host "Steam username for automated downloads via /download [Enter = skip, manual scripts only]"
    $srvPass   = Read-Host "Arma server password for players [Enter = none]"
    do { $admPass = Read-Host "Arma admin password (#login)" } while (-not $admPass)

    # Standard values - only asked with -Advanced
    $svcName     = "Arma3Server"
    $hcName      = "Arma3HeadlessClient"
    $serverBase  = "C:\steamgames\a3server"
    $steamcmdDir = "C:\steamcmd"
    if ($Advanced) {
        $v = Read-Host "Arma server service name [$svcName]";        if ($v) { $svcName = $v }
        $v = Read-Host "Headless client service name [$hcName]";     if ($v) { $hcName = $v }
        $v = Read-Host "Arma server folder [$serverBase]";           if ($v) { $serverBase = $v }
        $v = Read-Host "SteamCMD folder [$steamcmdDir]";             if ($v) { $steamcmdDir = $v }
    } else {
        Write-Host "Using standard values (run with -Advanced to change): services $svcName/$hcName, $serverBase, $steamcmdDir" -ForegroundColor DarkGray
    }

    if (-not (Test-Path $serverBase)) {
        Write-Host "Warning: $serverBase does not exist (yet) - the bot expects the server installed there." -ForegroundColor Yellow
    }

    @"
# A3Bot configuration - generated by install.ps1
BOT_TOKEN=$botToken
GUILD_ID=$guildId
AUTHORIZED_USER_IDS=$userIds

# Windows Services
SERVICE_NAME=$svcName
HC_SERVICE_NAME=$hcName

# A2S query (joinability polling / player count)
QUERY_HOST=127.0.0.1
QUERY_PORT=2303

# Steam username with cached SteamCMD login (enables /download)
STEAM_USERNAME=$steamUser

# Arma server passwords (written into server.cfg by /setup_apply - never asked via Discord)
SERVER_PASSWORD=$srvPass
ADMIN_PASSWORD=$admPass
# Paths
SERVER_BASE=$serverBase
WORKSHOP_BASE=$steamcmdDir\steamapps\workshop\content\107410
STEAMCMD=$steamcmdDir\steamcmd.exe
"@ | Set-Content -Encoding UTF8 $envFile
    Write-Host ".env_setup written." -ForegroundColor Green
}

# 5. Validate SteamCMD installation (path from .env_setup) - skipped with -BotOnly
if ($BotOnly) {
    Write-Host "-BotOnly: skipping SteamCMD validation." -ForegroundColor DarkGray
    $steamcmdExe = $null
} else {
$steamcmdExe = (Get-Content $envFile | Where-Object { $_ -match '^STEAMCMD=' }) -replace '^STEAMCMD=', ''
if (-not $steamcmdExe) { $steamcmdExe = "C:\steamcmd\steamcmd.exe" }
if (-not (Test-Path $steamcmdExe)) {
    Write-Host "SteamCMD not found at $steamcmdExe" -ForegroundColor Yellow
    $dl = Read-Host "Download and install SteamCMD there now? [Y/n]"
    if ($dl -ne "n") {
        $steamcmdDir = Split-Path $steamcmdExe -Parent
        New-Item -ItemType Directory -Force $steamcmdDir | Out-Null
        $zip = Join-Path $env:TEMP "steamcmd.zip"
        Write-Host "Downloading SteamCMD..." -ForegroundColor Cyan
        Invoke-WebRequest "https://steamcdn-a.akamaihd.net/client/installer/steamcmd.zip" -OutFile $zip
        Expand-Archive $zip -DestinationPath $steamcmdDir -Force
        Remove-Item $zip
        if (Test-Path $steamcmdExe) {
            Write-Host "SteamCMD installed." -ForegroundColor Green
        } else {
            Write-Host "SteamCMD install failed - mod downloads will not work until fixed." -ForegroundColor Red
        }
    } else {
        Write-Host "Skipped - mod downloads (/setup_script) will not work until SteamCMD exists at $steamcmdExe." -ForegroundColor Yellow
    }
} else {
    Write-Host "Using SteamCMD: $steamcmdExe"
}
}

# 6. Install dependencies
Write-Host "Installing Python dependencies..." -ForegroundColor Cyan
& $python -m pip install --upgrade discord.py python-a2s python-dotenv
if ($LASTEXITCODE -ne 0) { Write-Host "pip install failed." -ForegroundColor Red; exit 1 }

# 7. Create dirs
New-Item -ItemType Directory -Force $logsDir | Out-Null
New-Item -ItemType Directory -Force (Join-Path $PSScriptRoot "profiles_store") | Out-Null

# 8. Register the service (skip if it already exists)
& $nssm status $service *>$null
if ($LASTEXITCODE -eq 0) {
    Write-Host "Service $service already exists - skipping install." -ForegroundColor Yellow
} else {
    Write-Host "Registering service $service..." -ForegroundColor Cyan
    & $nssm install $service $python
    & $nssm set $service AppParameters "`"$botFile`""
    & $nssm set $service AppDirectory $botDir
    & $nssm set $service AppExit Default Restart
    & $nssm set $service AppStdout (Join-Path $logsDir "a3bot_stdout.log")
    & $nssm set $service AppStderr (Join-Path $logsDir "a3bot_stderr.log")
}

# 9. Start
& $nssm start $service
Write-Host "Service $service started. Logs: $logsDir\a3bot_stderr.log" -ForegroundColor Green

# 10. Post-install notes
$steamUserCfg = ((Get-Content $envFile | Where-Object { $_ -match '^STEAM_USERNAME=' }) -replace '^STEAM_USERNAME=', '').Trim()
if ($steamUserCfg -and -not $BotOnly) {
    Write-Host ""
    Write-Host "-- One-time SteamCMD login (required for /download) --" -ForegroundColor Cyan
    Write-Host "Steam Guard needs an interactive prompt once:" -ForegroundColor Yellow
    Write-Host "  & `"$steamcmdExe`" +login $steamUserCfg +quit" -ForegroundColor Yellow
    Write-Host "The cached session belongs to the Windows account that runs it." -ForegroundColor Yellow
    Write-Host "$service runs as LocalSystem by default, which has its own empty cache." -ForegroundColor Yellow
    Write-Host "If /download finds nothing, run the service as that account instead:" -ForegroundColor Yellow
    Write-Host "  & `"$nssm`" set $service ObjectName `".\$env:USERNAME`" `"WINDOWS_PASSWORD`"" -ForegroundColor Yellow
    Write-Host "  & `"$nssm`" restart $service" -ForegroundColor Yellow
}
Write-Host ""
Write-Host "Next: run /help in Discord." -ForegroundColor Green
Write-Host "Done." -ForegroundColor Cyan
